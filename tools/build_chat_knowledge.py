"""Build api/data/site-content.json: the website text the chat assistant can draw on.

Run after any change to the site's pages:
    python3 tools/build_chat_knowledge.py

It pulls the readable text from each page, but leaves out sections that are
illustrative or not yet accurate, so the assistant never repeats them as fact:
  - home page "How it works" (#how): describes automation that doesn't exist yet
  - home page "The Engine" (#engine): an illustrative demo with made-up numbers
  - home page "News" (#news): loaded live from Winetitles, not ours
  - illustrative graphics (anything marked aria-hidden, the example pallet)
Remove an id from SKIP_IDS once that section has been rewritten honestly.
"""
import json
import os
import re

from bs4 import BeautifulSoup

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "api", "data", "site-content.json")

PAGES = [
    ("/", "index.html", "Home page"),
    ("/faq", "faq/index.html", "FAQ"),
    ("/vineyards", "vineyards/index.html", "For vineyards (register interest)"),
    ("/match", "match/index.html", "Find your match (buyer brief tool)"),
    ("/contact", "contact/index.html", "Contact"),
]
SKIP_IDS = {"how", "engine", "news"}
# Text fragments that mark illustrative content; any block containing one is dropped.
SKIP_TEXT = ["Illustrative order", "Illustrative run", "Consolidating order"]


def page_text(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        soup = BeautifulSoup(f.read(), "html.parser")
    for tag in soup(["script", "style", "noscript", "svg", "header", "footer", "nav", "form", "template"]):
        tag.decompose()
    for tag in soup.select('[aria-hidden="true"]'):
        tag.decompose()
    for sid in SKIP_IDS:
        for tag in soup.select("#" + sid):
            tag.decompose()
    main = soup.find("main") or soup.body or soup
    # The match tool only needs its first step (what a brief asks for).
    if path.startswith("match/"):
        first = main.select_one('[data-panel="1"]')
        main = first or main
    blocks = []
    for el in main.find_all(["h1", "h2", "h3", "h4", "p", "li", "summary", "dt", "dd", "label"]):
        if el.find(["p", "li", "h1", "h2", "h3", "h4"]):
            continue  # take the innermost text blocks only
        t = re.sub(r"\s+", " ", el.get_text(" ", strip=True)).strip()
        if not t or len(t) < 3:
            continue
        if any(s in t for s in SKIP_TEXT):
            continue
        if len(t) < 45 and re.search(r"\s\d{1,2}$", t):
            continue  # cells of the illustrative example pallet, e.g. "Shiraz Barossa 8"
        if el.name in ("h1", "h2", "h3"):
            t = "## " + t
        if blocks and blocks[-1] == t:
            continue
        blocks.append(t)
    return "\n".join(blocks)


def main():
    pages = []
    for url, path, title in PAGES:
        text = page_text(path)
        pages.append({"url": url, "title": title, "text": text})
        print(f"{url:12} {len(text):6} chars")
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump({"note": "Generated by tools/build_chat_knowledge.py - do not edit by hand.", "pages": pages}, f, ensure_ascii=False, indent=1)
    print("Wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
